#!/usr/bin/env python3
"""Regenerate public test vectors with Python's independent crypto implementations."""
import hashlib
import hmac
from pathlib import Path
from cryptography.hazmat.primitives import hashes, padding, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
from cryptography.hazmat.primitives.kdf.hkdf import HKDF

hashes_seen = {}


def sha(data):
    result = hashlib.sha256(data).digest()
    hashes_seen[data.hex()] = result.hex()
    return result


def mac(key, data):
    original = key
    if len(key) > 64:
        key = sha(key)
    key = key.ljust(64, b'\0')
    result = sha(bytes(x ^ 0x5c for x in key) + sha(bytes(x ^ 0x36 for x in key) + data))
    assert result == hmac.digest(original, data, 'sha256')
    return result


def derive(secret, salt, info, length):
    key, previous, result, index = mac(salt, secret), b'', b'', 0
    while len(result) < length:
        index += 1
        previous = mac(key, previous + info + bytes([index]))
        result += previous
    expected = HKDF(hashes.SHA256(), length, salt, info).derive(secret)
    assert expected == result[:length]
    return expected


def encode(value):
    if isinstance(value, bytes):
        return b's' + str(len(value)).encode() + b':' + value
    if isinstance(value, str):
        return encode(value.encode())
    if isinstance(value, int):
        raw = str(value).encode()
        return b'n' + str(len(raw)).encode() + b':' + raw
    entries = sorted((encode(k), encode(v)) for k, v in value.items())
    return b'a' + str(len(entries)).encode() + b':' + b''.join(k + v for k, v in entries)


vectors = {}
vectors['hmac1'] = mac(b'\x0b' * 20, b'Hi There')
vectors['hmac2'] = mac(b'Jefe', b'what do ya want for nothing?')
vectors['hmac_long'] = mac(b'\xaa' * 131, b'Test Using Larger Than Block-Size Key - Hash Key First')
vectors['hkdf1'] = derive(b'\x0b' * 22, bytes(range(13)), bytes(range(240, 250)), 42)

# Fixed PRIVATE scalars are public test material, never deployment keys.
ephemeral = ec.derive_private_key(11, ec.SECP256R1())
recipient = ec.derive_private_key(12, ec.SECP256R1())
for name, key in [('ephemeral', ephemeral), ('recipient', recipient)]:
    vectors[name] = key.public_key().public_bytes(serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo)
shared = ephemeral.exchange(ec.ECDH(), recipient.public_key())
vectors['shared'] = shared
vectors['recipient_private'] = recipient.private_bytes(serialization.Encoding.DER, serialization.PrivateFormat.PKCS8, serialization.NoEncryption())
key_id = sha(vectors['recipient'])
material = derive(shared, b'SpaceCross sealed logs v1', vectors['ephemeral'] + key_id, 48)
vectors['aes_key'] = material[:16]
iv = bytes(range(16))
plaintext = b'spacecross encryption test'
padder = padding.PKCS7(128).padder()
padded = padder.update(plaintext) + padder.finalize()
encryptor = Cipher(algorithms.AES(material[:16]), modes.CBC(iv)).encryptor()
ciphertext = encryptor.update(padded) + encryptor.finalize()
vectors['ciphertext'] = ciphertext
body = encode(dict(version=1, algorithm='ECDH-HKDF-SHA256-AES128CBC-HMACSHA256', key_id=key_id,
                   ephemeral=vectors['ephemeral'], iv=iv, ciphertext=ciphertext))
vectors['envelope'] = encode(dict(body=body, mac=mac(material[16:], body)))
destination = Path(__file__).resolve().parents[1] / 'spacecross/security/tests/stubs/vectors.lua'
destination.parent.mkdir(parents=True, exist_ok=True)
lines = ['-- Generated by tools/generate_crypto_vectors.py; public test keys only.', 'return {', '  hashes = {']
for source, result in sorted(hashes_seen.items()):
    lines.append(f'    ["{source}"] = "{result}",')
lines.append('  },')
for name, value in sorted(vectors.items()):
    lines.append(f'  {name} = "{value.hex()}",')
lines.append('}\n')
destination.write_text('\n'.join(lines))
print(destination)
